undangan = set()
webinar_A = set()
webinar_B = set()
undangan = set(input("Daftar undangan: ").split(","))
webinar_A = set(input("Peserta Webinar A: ").split(","))
webinar_B = set(input("Peserta Webinar B: ").split(","))
print("Semua peserta:", webinar_A | webinar_B)
print("Hadir keduanya:", webinar_A & webinar_B)
print("Hadir salah satu:", webinar_A ^ webinar_B)
print("Tidak hadir:", undangan - (webinar_A | webinar_B))